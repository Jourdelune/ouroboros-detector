def load_file(path: str | None) -> str:
    """Uploaded file -> the plain text shown in the box and analysed."""
    if not path:
        return ""
    try:
        return extract_text(path)
    except Exception as exc:  # shown to the user rather than crashing the app
        raise gr.Error(f"Could not read {Path(path).name}: {exc}")


def build_ui(state: DemoState) -> gr.Blocks:
    with gr.Blocks(title="Ouroboros — AI text detection", theme=gr.themes.Soft()) as ui:
        gr.Markdown(
            "# Ouroboros\n"
            "Token-level AI-text detection — an open reimplementation of "
            "**Pangram 4** ([arXiv:2607.27183](https://arxiv.org/abs/2607.27183)).\n\n"
            "The model labels **every token** as `human`, `ai-assisted` (co-written: human "
            "idea, AI wording) or `ai-generated`, then a linear-chain CRF turns those into "
            "clean, sentence-aligned segments."
        )

        with gr.Row():
            with gr.Column(scale=5):
                text_in = gr.Textbox(
                    label="Document",
                    placeholder="Paste at least 50 words…",
                    lines=16,
                )
                file_in = gr.File(
                    label="…or drop a file (PDF, DOCX, TXT, MD) — converted to plain text",
                    file_types=list(SUPPORTED),
                    type="filepath",
                    height=90,
                )
                with gr.Row():
                    run_btn = gr.Button("Analyse", variant="primary", scale=3)
                    clear_btn = gr.ClearButton(value="Clear", scale=1)
                norm_in = gr.Radio(
                    [NORM_FULL, NORM_UNWRAP, NORM_NONE],
                    value=NORM_FULL,
                    label="Layout normalization",
                    info="Full: on 800 test docs, false positives 0.75% → 4.25% on already-clean "
                    "text, but it fixes pasted PDF text. Re-join only: touches hard-wrapped text only.",
                )
                gr.Examples(
                    examples=EXAMPLES,
                    inputs=text_in,
                    label="Try: human · AI · spliced (human then AI)",
                )

            with gr.Column(scale=5):
                summary_md = gr.Markdown()
                notes_md = gr.Markdown()
                fractions = gr.Label(label="Character fractions by class", num_top_classes=3)
                humanizer = gr.Label(
                    label="Humanization probe (document level)", num_top_classes=4
                )

        gr.Markdown("### Segmentation")
        highlighted = gr.HighlightedText(
            label="Per-segment authorship",
            combine_adjacent=True,
            show_legend=True,
            color_map=LABEL_STYLE,
        )

        with gr.Tabs():
            with gr.Tab("Token probabilities"):
                gr.Markdown(
                    "What the token head believes about each word **before** calibration, "
                    "the CRF and sentence voting — the raw evidence the segmentation is "
                    "built from. Hover a word for its probability."
                )
                token_html = gr.HTML()
            with gr.Tab("Document AI-fraction distribution"):
                gr.Markdown(
                    "The segment head's distribution over the 15 buckets of the weighted "
                    "AI fraction (averaged over windows). Mass split between both ends "
                    "means the model sees two authors; mass in the middle means co-writing."
                )
                bucket_plot = gr.BarPlot(
                    x="f_AI bucket", y="probability", y_lim=[0, 1], height=260, sort=None
                )

        with gr.Accordion("Segment detail", open=False):
            table = gr.Dataframe(
                headers=["#", "label", "confidence", "chars", "length", "excerpt"],
                datatype=["number", "str", "str", "str", "number", "str"],
                wrap=True,
            )

        gr.Markdown(
            "<sub>Confidence is the mean CRF marginal over a segment's tokens: it measures "
            "how peaked the unconstrained posterior is, not the probability that the final "
            "constrained label is correct.</sub>"
        )

        gr.Markdown(
            "## Why? — explaining the prediction\n"
            "Each word is coloured by how much it pushed the **AI score** up (red) or "
            "down (green). *Word occlusion* re-scores the text with each word removed. "
            "*Gradient × Input* takes the derivative of the score with respect to each "
            "word's input embedding, times the embedding (one backward pass); "
            "*Integrated Gradients* averages that gradient along a path from an empty "
            "input. Gradients are cheap but noisy on an LLM backbone — cross-check them "
            "against occlusion. **Sentence occlusion** does the same per sentence."
        )
        with gr.Row():
            method_in = gr.Radio(
                list(METHOD_CHOICES), value=list(METHOD_CHOICES)[0], label="Method"
            )
            target_in = gr.Radio(
                list(TARGET_CHOICES), value=list(TARGET_CHOICES)[0], label="Score to explain"
            )
            with gr.Column():
                steps_in = gr.Slider(4, 64, value=16, step=4, label="IG steps")
                occlude_in = gr.Checkbox(value=True, label="Sentence occlusion")
        explain_btn = gr.Button("Explain", variant="secondary")
        explain_md = gr.Markdown()
        word_html = gr.HTML()
        with gr.Row():
            to_ai_table = gr.Dataframe(
                headers=["word", "mean attribution", "count"],
                datatype=["str", "str", "number"],
                label="Words pushing towards AI",
            )
            to_human_table = gr.Dataframe(
                headers=["word", "mean attribution", "count"],
                datatype=["str", "str", "number"],
                label="Words pushing towards human",
            )
        with gr.Accordion("Sentence occlusion", open=True):
            sentence_html = gr.HTML()
            sentence_table = gr.Dataframe(
                headers=["Δ score", "score without it", "sentence"],
                datatype=["str", "str", "str"],
                wrap=True,
            )
        gr.Markdown(
            "<sub>Attributions are local explanations of one differentiable score, not "
            "of the CRF decisions; subword attributions are summed per word. They show "
            "what the network *relies on*, which may be a style cue rather than a "
            "reason a human would accept.</sub>"
        )

        outputs = [
            highlighted, fractions, summary_md, humanizer, table, notes_md, token_html, bucket_plot
        ]
        run_btn.click(lambda t, n: analyse(t, state, n), inputs=[text_in, norm_in], outputs=outputs)
        text_in.submit(lambda t, n: analyse(t, state, n), inputs=[text_in, norm_in], outputs=outputs)
        file_in.upload(load_file, inputs=file_in, outputs=text_in).then(
            lambda t, n: analyse(t, state, n), inputs=[text_in, norm_in], outputs=outputs
        )
        explain_outputs = [
            explain_md, word_html, to_ai_table, to_human_table, sentence_html, sentence_table
        ]
        explain_btn.click(
            lambda t, n, *a: explain(prepare(t, n)[0], *a, state),
            inputs=[text_in, norm_in, method_in, target_in, steps_in, occlude_in],
            outputs=explain_outputs,
        )
        clear_btn.add([text_in, file_in, *outputs, *explain_outputs])

    return ui


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--run-dir",
        default=os.environ.get("OUROBOROS_RUN", "runs/stage2"),
        help="A released model directory / Hugging Face repo id, or a training run directory (checkpoint/ + config.yaml)",
    )
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--port", type=int, default=7860)
    parser.add_argument("--share", action="store_true", help="Create a public gradio link")
    args = parser.parse_args()

    run_dir = Path(args.run_dir)
    released = (run_dir / "ouroboros_config.yaml").exists() or not run_dir.exists()  # local release dir or hub id
    if not released and not (run_dir / "checkpoint").exists():
        raise SystemExit(
            f"no checkpoint in {run_dir}. Train first:\n"
            "  ouroboros train --config configs/stage1.yaml --stage2-config configs/stage2.yaml"
        )

    state = DemoState(str(run_dir), args.device)
    print(f"[demo] run dir: {run_dir}")
    build_ui(state).launch(server_port=args.port, share=args.share)


if __name__ == "__main__":
    main()
