"""Gradio demo for Ouroboros.

Paste a document, get back the character-aligned authorship segmentation the
model produces: per-token provenance decoded through the CRF, the document
verdict under the report's Section 5.1 rule, the class fractions, and the
four-way humanization probe.

The "Why?" section explains the prediction: word attributions from the
gradient of an AI score with respect to the input embeddings (Gradient x Input
or Integrated Gradients), and sentence occlusion (re-score without each sentence).
"""

